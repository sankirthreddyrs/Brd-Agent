"""Clarification question domain models for the BRD Agent.

Defines questions generated by the AI agent when requirements contain gaps or ambiguity.
"""

from datetime import datetime
from enum import Enum
from typing import Literal, Optional
from pydantic import BaseModel, ConfigDict, Field


class AnswerFormat(str, Enum):
    """Supported input formats for answering questions."""

    TEXT = "TEXT"
    CHOICE = "CHOICE"
    DATE = "DATE"
    NUMBER = "NUMBER"
    YES_NO = "YES_NO"


class Question(BaseModel):
    """Clarification question presented to the user to resolve requirement gaps.

    Attributes:
        id: Unique identifier for the question (e.g., Q-001).
        project_id: Identifier of the project this question belongs to.
        field_path: Target field or requirement topic being clarified.
        question_text: The question posed to the user.
        why_it_matters: Context explaining the architectural/business impact of the gap.
        answer_format: Expected input type (TEXT, CHOICE, DATE, NUMBER, YES_NO).
        options: Permitted choices if answer_format is CHOICE.
        impact: Business/technical impact score (1=low, 2=medium, 3=high).
        gap_confidence: Agent's confidence that a genuine information gap exists (0.0 to 1.0).
        priority: Ranking metric computed as (impact * gap_confidence).
        status: Lifecycle status of the question ('open', 'answered', 'skipped').
        created_at: Timestamp when the question was generated.
    """

    model_config = ConfigDict(use_enum_values=False)

    id: str = Field(..., description="Unique question identifier")
    project_id: str = Field(..., description="Associated project ID")
    field_path: str = Field(..., description="Target field path or section")
    question_text: str = Field(..., description="Clarification question text")
    why_it_matters: str = Field(
        ...,
        description="Explanation of why this information is needed for BRD completion",
    )
    answer_format: AnswerFormat = Field(
        ...,
        description="Expected format of the answer",
    )
    options: Optional[list[str]] = Field(
        default=None,
        description="List of options when answer_format is CHOICE",
    )
    impact: int = Field(
        ...,
        ge=1,
        le=3,
        description="Impact score: 1 (low), 2 (medium), 3 (high)",
    )
    gap_confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Gap detection confidence score between 0.0 and 1.0",
    )
    priority: float = Field(
        default=0.0,
        description="Computed priority ranking score: impact * gap_confidence",
    )
    status: Literal["open", "answered", "skipped"] = Field(
        default="open",
        description="Current status of the question",
    )
    created_at: datetime = Field(
        ...,
        description="Timestamp when question was created",
    )

    def compute_priority(self) -> float:
        """Compute, store, and return the priority score: impact * gap_confidence."""
        calc = self.impact * self.gap_confidence
        self.priority = calc
        return calc
