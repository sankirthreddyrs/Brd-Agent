"""Pydantic schemas for structured LLM outputs in the BRD Agent.

Defines schemas passed to Gemini for JSON mode / structured decoding.
"""

from typing import Optional, Union
from pydantic import BaseModel, ConfigDict, Field

from app.models.assumption import Assumption
from app.models.question import AnswerFormat
from app.models.requirement import Requirement
from app.models.validation import Severity


class CandidateIssue(BaseModel):
    """Potential ambiguity, contradiction, or gap detected by LLM advisory analysis."""

    model_config = ConfigDict(use_enum_values=False)

    description: str = Field(
        ...,
        description="Detailed description of the potential issue or ambiguity",
    )
    related_requirement_ids: list[str] = Field(
        default_factory=list,
        description="IDs of requirements involved in the issue",
    )
    suggested_severity: Severity = Field(
        default=Severity.WARNING,
        description="Advisory severity suggested by the model",
    )


class GapAnalysisResult(BaseModel):
    """Container for advisory review candidates flagged by Gemini."""

    model_config = ConfigDict(use_enum_values=False)

    candidate_issues: list[CandidateIssue] = Field(
        default_factory=list,
        description="List of candidate issues flagged during gap analysis",
    )


class QuestionDraft(BaseModel):
    """Pydantic schema for Gemini to draft a single clarification question."""

    model_config = ConfigDict(use_enum_values=False)

    question_text: str = Field(
        ...,
        description="Clear, non-technical clarification question tailored for a business stakeholder",
    )
    why_it_matters: str = Field(
        ...,
        description="One-sentence explanation of why answering this question is critical to requirements completion",
    )
    answer_format: AnswerFormat = Field(
        default=AnswerFormat.TEXT,
        description="Expected answer input format (TEXT, CHOICE, DATE, NUMBER, YES_NO)",
    )
    options: Optional[list[str]] = Field(
        default=None,
        description="List of choices if answer_format is CHOICE, otherwise null",
    )


class ExtractedRequirementDraft(Requirement):
    """Candidate requirement draft generated by LLM extraction with source chunk citations."""

    source_chunk_ids: list[str] = Field(
        default_factory=list,
        description="IDs of source document chunks directly grounding this requirement",
    )
    rationale: Optional[str] = Field(
        default=None,
        description="Optional reasoning or context for extraction",
    )


RawExtractedRequirement = ExtractedRequirementDraft


class ExtractionResult(BaseModel):
    """Structured extraction output containing requirements and proposed assumptions."""

    model_config = ConfigDict(use_enum_values=False)

    requirements: list[Union[ExtractedRequirementDraft, Requirement]] = Field(
        default_factory=list,
        description="Candidate requirements extracted from the business idea and source document chunks",
    )
    proposed_assumptions: list[Assumption] = Field(
        default_factory=list,
        description="Explicit assumptions proposed where reasonable defaults were adopted",
    )
