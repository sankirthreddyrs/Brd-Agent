-- ====================================================================
-- BRD AGENT - DATABASE SCHEMA (SUPABASE POSTGRES)
-- ====================================================================
-- This SQL script creates the core schema for the BRD Agent backend.
-- All table definitions map directly to the Pydantic domain models:
--   - projects               -> app.models.project.Project
--   - requirements           -> app.models.requirement.Requirement
--   - questions              -> app.models.question.Question
--   - answers                -> app.models.answer.Answer
--   - assumptions            -> app.models.assumption.Assumption
--   - validation_issues      -> app.models.validation.ValidationIssue
--   - source_documents       -> app.models.document.SourceDocument (used in Day 4)
--   - source_chunks          -> app.models.document.SourceChunk (used in Day 4)
--   - brd_document_versions  -> app.models.document.BRDDocumentVersion (used in Day 6)
--   - state_transitions      -> Audit log for app.core.state_machine.ProjectStateMachine
-- ====================================================================

-- Enable pgcrypto for gen_random_uuid() if not enabled
create extension if not exists "pgcrypto";

-- --------------------------------------------------------------------
-- 1. PROJECTS TABLE
-- --------------------------------------------------------------------
create table if not exists projects (
    id uuid primary key default gen_random_uuid(),
    title text not null,
    idea text not null,
    status text not null default 'DRAFT',
    input_revision int not null default 1,
    previous_valid_status text,  -- Stored state for recovering from FAILED status via retry
    last_error text,             -- Error diagnostic message when status is FAILED
    created_at timestamptz default now(),
    updated_at timestamptz default now()
);

-- --------------------------------------------------------------------
-- 2. REQUIREMENTS TABLE
-- Requirement IDs (e.g. REQ-001) are generated by extraction engine.
-- --------------------------------------------------------------------
create table if not exists requirements (
    id text primary key,
    project_id uuid not null references projects(id) on delete cascade,
    type text not null,         -- functional, nonfunctional, business, constraint
    title text not null,
    statement text not null,
    actor text,
    outcome text,
    priority text not null default 'SHOULD',
    acceptance_criteria jsonb default '[]'::jsonb,
    trace_refs jsonb default '[]'::jsonb,
    confidence float not null default 1.0,
    created_at timestamptz default now()
);

-- --------------------------------------------------------------------
-- 3. QUESTIONS TABLE
-- Question IDs (e.g. Q-xxxx) generated by question engine.
-- --------------------------------------------------------------------
create table if not exists questions (
    id text primary key,
    project_id uuid not null references projects(id) on delete cascade,
    field_path text not null,
    question_text text not null,
    why_it_matters text not null,
    answer_format text not null,
    options jsonb,
    impact int not null,
    gap_confidence float not null,
    priority float not null default 0,
    status text not null default 'open', -- open, answered, skipped
    created_at timestamptz default now()
);

-- --------------------------------------------------------------------
-- 4. ANSWERS TABLE
-- Answer IDs (e.g. ANS-xxxx) linked to stakeholder questions.
-- --------------------------------------------------------------------
create table if not exists answers (
    id text primary key,
    project_id uuid not null references projects(id) on delete cascade,
    question_id text not null references questions(id) on delete cascade,
    value text not null,
    answered_at timestamptz default now()
);

-- --------------------------------------------------------------------
-- 5. ASSUMPTIONS TABLE
-- Assumption IDs (e.g. ASM-xxxx) generated for reasonable defaults.
-- --------------------------------------------------------------------
create table if not exists assumptions (
    id text primary key,
    project_id uuid not null references projects(id) on delete cascade,
    statement text not null,
    rationale text not null,
    impact text not null,        -- LOW, MEDIUM, HIGH
    status text not null default 'PROPOSED', -- PROPOSED, ACCEPTED, REJECTED, SUPERSEDED
    linked_requirement_ids jsonb default '[]'::jsonb,
    created_at timestamptz default now()
);

-- --------------------------------------------------------------------
-- 6. VALIDATION ISSUES TABLE
-- Active findings from the rule engine.
-- --------------------------------------------------------------------
create table if not exists validation_issues (
    id uuid primary key default gen_random_uuid(),
    project_id uuid not null references projects(id) on delete cascade,
    code text not null,
    severity text not null,      -- blocker, warning
    field_path text not null,
    entity_id text,
    message text not null,
    created_at timestamptz default now()
);

-- --------------------------------------------------------------------
-- 7. SOURCE DOCUMENTS TABLE (Placeholder for ingestion in Day 4)
-- --------------------------------------------------------------------
create table if not exists source_documents (
    id uuid primary key default gen_random_uuid(),
    project_id uuid not null references projects(id) on delete cascade,
    filename text not null,
    file_type text not null,     -- pdf, docx, txt
    status text not null default 'uploaded', -- uploaded, extracting, ready, failed
    storage_path text,
    error_message text,
    created_at timestamptz default now()
);

-- --------------------------------------------------------------------
-- 8. SOURCE CHUNKS TABLE (Placeholder for grounding in Day 4)
-- --------------------------------------------------------------------
create table if not exists source_chunks (
    id uuid primary key default gen_random_uuid(),
    document_id uuid not null references source_documents(id) on delete cascade,
    project_id uuid not null references projects(id) on delete cascade,
    text text not null,
    page_number int,
    heading text,
    chunk_index int not null
);

-- --------------------------------------------------------------------
-- 9. BRD DOCUMENT VERSIONS TABLE (Placeholder for generation in Day 6)
-- --------------------------------------------------------------------
create table if not exists brd_document_versions (
    id uuid primary key default gen_random_uuid(),
    project_id uuid not null references projects(id) on delete cascade,
    version int not null,
    input_revision int not null,
    content_json jsonb not null,
    docx_path text,
    model_used text not null,
    prompt_version text not null,
    generated_at timestamptz default now(),
    quality_check_passed boolean not null default false,
    is_current boolean not null default true,
    constraint uq_project_version unique (project_id, version)
);

-- --------------------------------------------------------------------
-- 10. STATE TRANSITIONS AUDIT LOG
-- Records state machine transition history.
-- --------------------------------------------------------------------
create table if not exists state_transitions (
    id uuid primary key default gen_random_uuid(),
    project_id uuid not null references projects(id) on delete cascade,
    from_state text not null,
    to_state text not null,
    event text not null,
    created_at timestamptz default now()
);

-- --------------------------------------------------------------------
-- INDEXES
-- --------------------------------------------------------------------
create index if not exists idx_requirements_project_id on requirements(project_id);
create index if not exists idx_questions_project_id on questions(project_id);
create index if not exists idx_questions_status on questions(project_id, status);
create index if not exists idx_answers_project_id on answers(project_id);
create index if not exists idx_assumptions_project_id on assumptions(project_id);
create index if not exists idx_validation_issues_project_id on validation_issues(project_id);
create index if not exists idx_source_documents_project_id on source_documents(project_id);
create index if not exists idx_source_chunks_doc_proj on source_chunks(document_id, project_id);
create index if not exists idx_brd_versions_project_id on brd_document_versions(project_id);
create index if not exists idx_state_transitions_project_id on state_transitions(project_id);

